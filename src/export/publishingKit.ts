import type { Project } from '../types';
import { buildTimeline, formatTime, type Timeline, type VoiceTiming } from '../animation/timeline';
import { projectHook } from '../data/projectText';
import { SOURCES } from '../data/sources';

/**
 * A plain-text publishing kit: title options, a factual description with
 * chapters computed from the real timeline, sources, tags, and the Short's
 * caption. Everything here is a starting point to edit, not a guarantee of reach
 * or monetization.
 */

const mmss = (t: number) => {
  const s = Math.max(0, Math.round(t));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

/** YouTube chapters: first at 0:00, each at least 10 s (short scenes merge forward). */
export function youtubeChapters(tl: Timeline): string[] {
  const out: { start: number; end: number; title: string }[] = [];
  for (const span of tl.spans) {
    const last = out[out.length - 1];
    if (last && last.end - last.start < 10) {
      last.end = span.end;
      last.title = `${last.title} / ${span.scene.title}`;
    } else {
      out.push({ start: out.length ? span.start : 0, end: span.end, title: span.scene.title });
    }
  }
  const tail = out[out.length - 1];
  if (out.length > 1 && tail.end - tail.start < 10) {
    const prev = out[out.length - 2];
    prev.end = tail.end;
    prev.title = `${prev.title} / ${tail.title}`;
    out.pop();
  }
  return out.map((c) => `${mmss(c.start)} ${c.title}`);
}

export function buildPublishingKit(project: Project, voice?: VoiceTiming | null): string {
  const long = buildTimeline({ ...project, settings: { ...project.settings, aspect: '16:9' } }, undefined, voice);
  const short = buildTimeline({ ...project, settings: { ...project.settings, aspect: '9:16' } }, undefined, voice);
  const src = SOURCES.map((s) => `- ${s.title.split(' — ')[0]} (${s.date}): ${s.url}`).join('\n');
  const L: string[] = [];
  L.push('THE FOX FILES — PUBLISHING KIT');
  L.push(`Episode: ${project.episodeTitle}`);
  L.push('Generated by Fox Files Studio. Read and edit every line before you post.');
  L.push('');
  L.push('==================== YOUTUBE (16:9) ====================');
  L.push(`Length: ${formatTime(long.total)}`);
  L.push('');
  L.push('TITLE OPTIONS');
  L.push('1. MKUltra: What the CIA Records Actually Show');
  L.push('2. The CIA Drugged People Who Never Knew: the MKUltra Record, Animated');
  L.push('3. MKUltra in 90 Seconds, Straight From the 1977 Senate Hearing');
  L.push('');
  L.push('DESCRIPTION');
  L.push(
    'In August 1977, CIA Director Stansfield Turner testified to the U.S. Senate about MKUltra, a CIA program of research in behavioral modification that ran from 1953 to 1964. The surviving financial records listed 149 subprojects at 80 institutions, and six subprojects tested drugs on people who did not know. Many program files had been destroyed in 1973.',
  );
  L.push('');
  L.push('Agent Fox walks through what the record shows, and what it does not.');
  L.push('');
  L.push('CHAPTERS');
  L.push(...youtubeChapters(long));
  L.push('');
  L.push('SOURCES');
  L.push(src);
  L.push('');
  L.push('This is an animated documentary. Documents on screen are illustrations; the narration paraphrases the public record.');
  L.push('');
  L.push('TAGS');
  L.push('MKUltra, CIA, history, documentary, animated documentary, Cold War, Church Committee, Senate hearing 1977, Frank Olson, declassified');
  L.push('');
  L.push('============ SHORT / REELS / TIKTOK (9:16) ============');
  L.push(`Length: ${formatTime(short.total)} (hook + episode)`);
  L.push('');
  L.push(`HOOK (first ${short.hook ? short.hook.end.toFixed(1) : '0'} s)`);
  L.push(`"${projectHook(project, project.settings.language)?.text ?? ''}"`);
  L.push('');
  L.push('CAPTION');
  L.push('The CIA tested drugs on people who never knew. This is from the 1977 Senate hearing. Full sources in the comments.');
  L.push('');
  L.push('HASHTAGS');
  L.push('#MKUltra #CIA #History #Documentary #DeclassifiedHistory #Shorts');
  L.push('');
  L.push('PINNED COMMENT');
  L.push(`Source: ${SOURCES[0].title.split(' — ')[0]}, ${SOURCES[0].date}: ${SOURCES[0].url}`);
  L.push('');
  L.push('==================== BEFORE YOU POST ====================');
  L.push('- Record your own voice-over from the narration script if you can. Your own voice and commentary make the channel clearly original.');
  L.push('- Upload the .srt file as captions.');
  L.push('- Keep the series format, but vary each episode (topic, structure, visuals). YouTube can demonetize mass-produced, repetitive content.');
  L.push('- If you use an AI voice, check YouTube’s "altered or synthetic content" setting when uploading.');
  L.push('- Mid-roll ads need videos of 8 minutes or more; this episode is a short-form piece.');
  return L.join('\n');
}
