"""
Trace Agent Fox's FRONT face (eyes, pupils, brows) from the approved front face render, in the same
format as tools/trace_face.py, for the front rig (character/foxFront.ts).

The render (art/incoming/pieces/front/face_v2.png, approved in the manifest) shares its canvas with
the blank front head, so traced positions are also positions on the head sprite. Points are relative
to the near (viewer-left) eye centre in units of its white's height; `anchorPx` and `unitPx` give
that centre and unit in head-image pixels.

Usage: python tools/trace_front.py --ts ../fox-files-studio-editor/src/character/rig/frontFace.ts
"""
import argparse, json, os
import cv2, numpy as np
from scipy import ndimage as ndi
from trace_face import trace_eyes, profile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Face band of the 1040x1008 front render (eyes and brows), scaled so the eyes match the master trace's size.
CROP = (250, 340, 800, 650)
SCALE = 1.3


def approved(key):
    m = json.load(open(os.path.join(ROOT, 'art', 'incoming', 'manifest.json'), encoding='utf8'))['sheets']
    return [v for v in m[key]['versions'] if v['status'] == 'approved'][-1]['file']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ts', required=True)
    a = ap.parse_args()
    src = cv2.imread(os.path.join(ROOT, approved('front/face')))
    x0, y0, x1, y1 = CROP
    img = cv2.resize(src[y0:y1, x0:x1], None, fx=SCALE, fy=SCALE, interpolation=cv2.INTER_CUBIC)
    eyes, brows, _ = trace_eyes(img, white_band=0.98)
    to_src = lambda x, y: (x0 + x / SCALE, y0 + y / SCALE)
    ox, oy = eyes['near']['centre']
    unit = eyes['near']['height']
    norm = lambda pts: [[round((x - ox) / unit, 4), round((y - oy) / unit, 4)] for x, y in pts]
    out = {'source': 'front face render (approved front/face)', 'eyes': {}, 'brows': {},
           'anchorPx': [round(v, 2) for v in to_src(ox, oy)], 'unitPx': round(unit / SCALE, 3)}
    N = 81
    for side, e in eyes.items():
        sil, wh = e['silhouette'], e['white']
        pcx, pcy, pa, pb, pang = e['pupil']
        xs = np.linspace(sil[:, 0].min() + 0.5, sil[:, 0].max() - 0.5, N)
        st, sb = profile(sil, xs)
        wt, wb = profile(wh, xs)
        ok = ~np.isnan(wt)
        idx = np.nonzero(ok)[0]
        mid = np.interp(xs, xs[idx], ((wt + wb) / 2)[idx])
        wt = np.where(ok, wt, np.clip(mid, st, sb))
        wb = np.where(ok, wb, np.clip(mid, st, sb))
        nx = lambda v: [round((x - ox) / unit, 4) for x in v]
        ny = lambda v: [round((y - oy) / unit, 4) for y in v]
        out['eyes'][side] = {
            'centre': norm([e['centre']])[0], 'width': round(e['width'] / unit, 4), 'height': round(e['height'] / unit, 4),
            'white': norm(wh[::2]), 'silhouette': norm(sil[::2]),
            'pupil': {'x': round((pcx - ox) / unit, 4), 'y': round((pcy - oy) / unit, 4), 'rx': round(min(pa, pb) / unit, 4), 'ry': round(max(pa, pb) / unit, 4)},
            'highlight': ({'x': round((e['hl'][0] - ox) / unit, 4), 'y': round((e['hl'][1] - oy) / unit, 4), 'r': round(e['hl'][2] / unit, 4)} if e['hl'] else None),
            'profile': {'x': nx(xs), 'silTop': ny(st), 'silBot': ny(sb), 'whiteTop': ny(wt), 'whiteBot': ny(wb)},
        }
    for side, b in brows.items():
        out['brows'][side] = norm(b[::2])
    dbg = img.copy()
    for e in eyes.values():
        cv2.polylines(dbg, [e['silhouette'].astype(np.int32)], True, (255, 0, 255), 2)
        cv2.polylines(dbg, [e['white'].astype(np.int32)], True, (255, 255, 0), 2)
    for b in brows.values():
        cv2.polylines(dbg, [b.astype(np.int32)], True, (0, 255, 255), 2)
    cv2.imwrite(os.path.join(ROOT, 'art', 'reference', 'trace', 'front_debug.png'), dbg)
    with open(a.ts, 'w', encoding='utf8') as f:
        f.write('// Generated by tools/trace_front.py from the approved front face render — do not edit by hand.\n')
        f.write('export const FRONT_FACE = ' + json.dumps(out) + ' as const;\n')
    print('front face traced; anchor', out['anchorPx'], 'unit px', out['unitPx'])


if __name__ == '__main__':
    main()
